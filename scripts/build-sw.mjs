import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? walk(path) : path;
    }),
  );
  return files.flat();
}

// Only application build outputs are precached. Uploaded photos never enter this list.
const files = (await walk(dist))
  .filter((file) => basename(file) !== "sw.js")
  .sort();
if (!files.some((file) => relative(dist, file) === "index.html")) {
  throw new Error(
    "Build the app with Vite before generating its service worker.",
  );
}
const version = createHash("sha256");
for (const file of files) {
  version.update(relative(dist, file));
  version.update(await readFile(file));
}
const cacheName = `pocketsense-${version.digest("hex").slice(0, 16)}`;
const assets = files.map(
  (file) => relative(dist, file).split("\\").join("/"),
);

const worker = `/* Generated by scripts/build-sw.mjs. Do not edit this build output. */
const BASE = new URL('./', self.location.href).pathname;
const PREFIX = 'pocketsense-scope-' + encodeURIComponent(BASE) + '-';
const CACHE = PREFIX + ${JSON.stringify(cacheName)};
const ASSETS = ${JSON.stringify(assets)}.map((file) => BASE + file);
const INDEX = BASE + 'index.html';
const APP_URLS = new Set(ASSETS);

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(ASSETS.map((url) => new Request(url, { cache: 'reload' })));
  })());
  // No skipWaiting: an open app retains a consistent release until its tabs close.
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      return (await cache.match(INDEX)) || fetch(request);
    })());
    return;
  }
  if (!APP_URLS.has(url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    return (await cache.match(url.pathname)) || fetch(request);
  })());
});
`;

await writeFile(join(dist, "sw.js"), worker);
console.log(`Offline worker: ${assets.length} bundled assets, ${cacheName}`);
